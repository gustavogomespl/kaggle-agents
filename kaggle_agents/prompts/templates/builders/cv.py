def build_multi_seed_instructions(working_dir: str, component_name: str) -> list[str]:
    """Build multi-seed training instructions for ensemble diversity."""
    return [
        "\n🎲 MULTI-SEED TRAINING (ENSEMBLE DIVERSITY):",
        "  - Train the SAME model architecture with DIFFERENT random seeds",
        "  - KEEP the injected canonical folds fixed - only change model randomness",
        "  - VALIDATE complete OOF before including in average",
        "    ```python",
        "    seeds = [42, 1337, 2024, 7, 123]",
        f"    canonical_dir = Path('{working_dir}') / 'canonical'",
        "    folds = np.load(canonical_dir / 'folds.npy')",
        "    canonical_train_ids = np.load(canonical_dir / 'train_ids.npy', allow_pickle=True)",
        "    valid_oof, valid_test = [], []",
        "",
        "    for seed in seeds:",
        "        try:",
        "            model = LGBMClassifier(random_state=seed, ...)  # Only change seed",
        "            oof, test = train_cv(model, folds)  # SAME folds",
        "",
        "            # VALIDATE: exact canonical shape and finite coverage.",
        "            if oof.shape[0] != len(canonical_train_ids):",
        "                raise ValueError('Seed OOF row count violates canonical contract')",
        "            eligible_oof = oof[CANONICAL_OOF_ELIGIBLE_MASK]",
        "            warmup_oof = oof[~CANONICAL_OOF_ELIGIBLE_MASK]",
        "            if not np.all(np.isfinite(eligible_oof)) or not np.all(np.isfinite(test)):",
        "                raise ValueError('Seed produced non-finite or incomplete predictions')",
        "            if warmup_oof.size and not np.isnan(warmup_oof).all():",
        "                raise ValueError('Seed fabricated temporal warm-up OOF coverage')",
        "",
        "            valid_oof.append(oof)",
        "            valid_test.append(test)",
        "            print(f'   ✅ Seed {seed}: complete OOF, included in average')",
        "        except (RuntimeError, ValueError, OSError) as e:",
        "            print(f'   ⚠️ Seed {seed} failed: {e}')",
        "            continue",
        "",
        "    if len(valid_oof) == 0:",
        "        raise ValueError('No seed produced valid OOF')",
        "",
        "    # Average only valid seeds",
        "    final_oof = np.mean(valid_oof, axis=0)",
        "    final_test = np.mean(valid_test, axis=0)",
        "    class_order = None",
        "    if (",
        "        IS_CLASSIFICATION and TARGET_TYPE == 'single'",
        "        and final_test.ndim == 2 and final_test.shape[1] > 1",
        "    ):",
        "        class_order = list(CANONICAL_METADATA.get('class_order') or [])",
        "        if len(class_order) != final_test.shape[1]:",
        "            raise ValueError('Canonical multiclass class_order is missing or misaligned')",
        "    save_component_artifacts(",
        "        final_oof, final_test, class_order=class_order",
        "    )",
        "    print(f'   Multi-seed: average of {len(valid_oof)}/{len(seeds)} seeds')",
        "    ```",
        "  - DO NOT create separate folds per seed (complexity + misalignment risk)",
    ]


def build_oof_hygiene_instructions(working_dir: str, component_name: str) -> list[str]:
    """Build OOF hygiene instructions for robust stacking."""
    return [
        "\nOOF HYGIENE (STACKING SAFETY):",
        "  - Initialize OOF with NaN and validate it BEFORE saving: exact canonical shape and finite values on `CANONICAL_OOF_ELIGIBLE_MASK`.",
        "  - Temporal warm-up rows (`~CANONICAL_OOF_ELIGIBLE_MASK`) MUST remain NaN and MUST never enter metric/ensemble fitting.",
        "  - Save fold assignments used for each row (enables leakage checks):",
        "    ```python",
        f"    canonical_dir = Path('{working_dir}') / 'canonical'",
        "    fold_assignment = np.load(canonical_dir / 'folds.npy')",
        "    canonical_train_ids = np.load(canonical_dir / 'train_ids.npy', allow_pickle=True)",
        "    if len(fold_assignment) != len(canonical_train_ids):",
        "        raise ValueError('Canonical fold/ID length mismatch')",
        f"    np.save(str(Path('{working_dir}') / 'models' / 'fold_assignment_{component_name}.npy'), fold_assignment)",
        "    ```",
        "  - Ensure train row order is consistent: use the same index/order for X, y, and OOF.",
        "  - Never drop, duplicate, or reorder canonical training rows inside a model component.",
    ]


