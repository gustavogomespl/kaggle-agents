def build_cv_instructions(working_dir: str, component_name: str) -> list[str]:
    """Build cross-validation instructions."""
    return [
        "\n🔄 CONSISTENT CROSS-VALIDATION (CRITICAL - USE CANONICAL FOLDS):",
        f"  - **MANDATORY**: Load canonical folds from `{working_dir}/canonical/folds.npy`",
        f"  - **MANDATORY**: Load canonical train_ids from `{working_dir}/canonical/train_ids.npy`",
        "  - **NEVER** create your own KFold/StratifiedKFold - canonical folds are already optimized",
        "    ```python",
        "    from pathlib import Path",
        "    import numpy as np",
        "",
        f"    canonical_dir = Path('{working_dir}') / 'canonical'",
        "    folds = np.load(canonical_dir / 'folds.npy')",
        "    train_ids = np.load(canonical_dir / 'train_ids.npy', allow_pickle=True)",
        "    with open(canonical_dir / 'metadata.json') as f:",
        "        canonical_metadata = json.load(f)",
        "    n_folds = int(canonical_metadata['n_folds'])",
        "",
        "    # `iter_canonical_cv_splits` is injected by the executor and is",
        "    # mandatory: for temporal CV, `folds != fold` leaks future rows.",
        "    for fold_idx, train_idx, val_idx in iter_canonical_cv_splits():",
        "        X_train, X_val = X[train_idx], X[val_idx]",
        "        y_train, y_val = y[train_idx], y[val_idx]",
        "        # ... train model on fold ...",
        "    ```",
        "  - NEVER replace `iter_canonical_cv_splits()` with `folds != fold`.",
        "  - Temporal folds use strict forward chaining and contain warm-up rows",
        "    marked fold=-1; those rows MUST remain NaN in OOF and MUST be",
        "    excluded only with `CANONICAL_OOF_ELIGIBLE_MASK` when scoring.",
        "  - WHY: Independent fold creation causes OOF misalignment → stacking ensemble fails",
        "  - CRITICAL: Fit FEATURE preprocessing/scalers INSIDE each CV fold (fit on X_train, transform X_val/X_test)",
        "  - EXCEPTION: TARGET LabelEncoder must be fit ONCE on FULL y BEFORE the CV loop (see tabular constraints)",
        f"  - CRITICAL: MUST save Out-of-Fold (OOF) predictions during CV to models/oof_{component_name}.npy",
        "  - OOF predictions enable proper stacking ensemble (meta-model trained on OOF)",
        "  - AFTER saving OOF/Test: print lines 'Saved OOF predictions to ...' and 'Saved test predictions to ...'",
        "  - Every candidate-produced .npy artifact must be pickle-free. Save "
        "text predictions, IDs, and class order as Unicode arrays (`dtype=str`), "
        "never `dtype=object`; the host rejects object/pickle arrays.",
        "  - MUST print 'Final Validation Performance: {score}'",
        "  - If the metric is NaN/inf, raise an error; never fabricate a replacement score",
        "  - Multiclass log_loss: after clipping, renormalize rows to sum to 1",
        "  - Initialize OOF with NaN; if any OOF-eligible canonical row remains unfilled after an early stop, checkpoint partial state and invalidate the candidate",
        "  - Treat class weighting/resampling as a candidate selected by the same validation protocol, not a mandatory default",
    ]


